#!/usr/bin/env node
/**
 * Builds the breed index in docs/breeds/README.md (David 2026-10-15: breed runs document
 * only in their own docs/breeds/<en-slug>.md; the shared docs point here).
 *
 * Inputs:
 *   docs/research/breed-registry.json   every breed of the register (species, order, names,
 *                                        slugs) — the list is never typed by hand. Availability
 *                                        is left out on purpose: a release record re-exports the
 *                                        register and must not make this index stale.
 *   docs/breeds/<en-slug>.md            one file per breed (optional; template: _TEMPLATE.md)
 *
 * The table between the markers in README.md is generated; everything else in README.md is
 * hand-written. Deterministic (no dates); a breed file whose slug is not in the register fails.
 *
 *   node scripts/breeds-index.mjs           rewrite the table
 *   node scripts/breeds-index.mjs --check   exit 1 when README.md is stale
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const BREEDS_DIR = 'docs/breeds';
export const INDEX = `${BREEDS_DIR}/README.md`;
export const REGISTRY = 'docs/research/breed-registry.json';
export const START = '<!-- breeds-index:start (generated by scripts/breeds-index.mjs — do not edit by hand) -->';
export const END = '<!-- breeds-index:end -->';

const SPECIES_SL = { dog: 'pes', cat: 'mačka' };

/** The breed files of docs/breeds (every `*.md` except README.md and `_*.md` templates). */
export function breedFiles(root = ROOT) {
  const dir = resolve(root, BREEDS_DIR);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md') && f !== 'README.md' && !f.startsWith('_'))
    .sort();
}

/** The value of a `**Stanje:** …` line of a breed file, or null. */
export function statusOf(markdown) {
  const m = /^\*\*Stanje:\*\*\s*(.+)$/m.exec(markdown);
  return m ? m[1].trim().replace(/\|/g, '\\|') : null;
}

/** The generated table (pure; used by the test). */
export function renderTable(registry, files) {
  const bySlug = new Map(registry.breeds.map((b) => [b.slug.en, b]));
  for (const f of Object.keys(files)) {
    if (!bySlug.has(f.replace(/\.md$/, ''))) throw new Error(`${BREEDS_DIR}/${f}: "${f.replace(/\.md$/, '')}" is not an English slug of ${REGISTRY}`);
  }
  const rows = [...registry.breeds]
    .sort((a, b) => registry.species.findIndex((s) => s.id === a.species) - registry.species.findIndex((s) => s.id === b.species) || a.order - b.order)
    .map((b) => {
      const file = `${b.slug.en}.md`;
      const doc = files[file] === undefined ? '— (zgodovina v skupnih dokumentih do 2026-10-15)' : `[${file}](${file})`;
      const status = files[file] === undefined ? '' : (statusOf(files[file]) ?? '');
      return `| ${b.name.sl} | ${b.name.en} | ${SPECIES_SL[b.species] ?? b.species} | \`${b.id}\` | ${doc} | ${status} |`;
    });
  return [
    START,
    `Pasem v registru: **${registry.breeds.length}** (${registry.species.map((s) => `${SPECIES_SL[s.id] ?? s.id}: ${s.breed_count}`).join(', ')}) — brezplačna osnova vrste (${registry.species.map((s) => s.free_plan.name.sl).join(', ')}) ni pasma registra.`,
    '',
    '| Pasma | Breed | Vrsta | Ključ | Dokument | Stanje (iz dokumenta) |',
    '|---|---|---|---|---|---|',
    ...rows,
    END,
  ].join('\n');
}

/** README.md with the table replaced (pure). */
export function renderIndex(readme, registry, files) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${INDEX}: markers missing`);
  return readme.slice(0, a) + renderTable(registry, files) + readme.slice(b + END.length);
}

export function currentIndex(root = ROOT) {
  const registry = JSON.parse(readFileSync(resolve(root, REGISTRY), 'utf8'));
  const files = Object.fromEntries(breedFiles(root).map((f) => [f, readFileSync(resolve(root, BREEDS_DIR, f), 'utf8')]));
  return renderIndex(readFileSync(resolve(root, INDEX), 'utf8'), registry, files);
}

function main(argv) {
  const next = currentIndex();
  const now = readFileSync(resolve(ROOT, INDEX), 'utf8');
  if (argv.includes('--check')) {
    if (next !== now) {
      console.error(`${INDEX} is stale — run: node scripts/breeds-index.mjs`);
      process.exit(1);
    }
    console.log(`${INDEX} is up to date`);
    return;
  }
  if (next !== now) writeFileSync(resolve(ROOT, INDEX), next);
  console.log(`breeds-index: ${next === now ? 'unchanged' : 'wrote'} ${INDEX}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
