/**
 * generate-api-types.mjs
 *
 * Fetches the OpenAPI 3.1 JSON spec from the running Laravel backend
 * and generates clean TypeScript interfaces & API client definitions
 * into mobile/src/api/schema.ts for the React Native app.
 *
 * Usage: npm run generate-api-types
 *
 * Prerequisites:
 *   1. The Laravel backend must be running (php artisan serve)
 *   2. The Scramble OpenAPI spec must be available at /docs/api.json
 */

import { writeFileSync, mkdirSync, existsSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

const API_BASE_URL = process.env.API_BASE_URL || 'http://localhost:8000';
const OPENAPI_SPEC_URL = `${API_BASE_URL}/docs/api.json`;
const OUTPUT_PATH = join(__dirname, '..', 'mobile', 'src', 'api', 'schema.ts');

async function main() {
  console.log('PetPrep — TypeScript SDK Generation');
  console.log('====================================');
  console.log(`Fetching OpenAPI spec from: ${OPENAPI_SPEC_URL}`);

  try {
    const response = await fetch(OPENAPI_SPEC_URL);

    if (!response.ok) {
      throw new Error(`HTTP ${response.status}: ${response.statusText}`);
    }

    const spec = await response.json();
    console.log(`✓ OpenAPI spec fetched successfully (${spec.info?.title || 'Unknown API'} v${spec.info?.version || '0.0.0'})`);

    // Ensure output directory exists
    const outputDir = dirname(OUTPUT_PATH);
    if (!existsSync(outputDir)) {
      mkdirSync(outputDir, { recursive: true });
      console.log(`✓ Created output directory: ${outputDir}`);
    }

    // Generate TypeScript types using openapi-typescript
    const { default: openapiTS } = await import('openapi-typescript');
    const typesOutput = await openapiTS(spec);

    // Add header comment
    const header = `/**
 * PetPrep API Schema — Auto-generated TypeScript definitions
 * Generated by: npm run generate-api-types
 * Source: ${OPENAPI_SPEC_URL}
 * 
 * DO NOT EDIT MANUALLY — regenerate via npm run generate-api-types
 */

`;

    writeFileSync(OUTPUT_PATH, header + typesOutput);
    console.log(`✓ TypeScript schema written to: ${OUTPUT_PATH}`);
    console.log('Done!');
  } catch (error) {
    console.error('✗ Failed to generate API types:', error.message);
    console.error('');
    console.error('Make sure the Laravel backend is running:');
    console.error('  cd backend && php artisan serve');
    process.exit(1);
  }
}

main();
