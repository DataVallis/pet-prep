use Throwable;

/**
 * Frugal clips — the reversed transition is dropped (David 2026-10-30, on his phone: when the
 * dog stands up it »looks like rewinding a tape backwards«). Since then `sleeping_to_idle` is
 * generated by fal again (MediaEntitlementService). This repairs the pets / looks that already
 * got the reversal (`pet_media.frugal_source = idle_to_sleeping`, no clip of their own):
 *
 *  - `plan()` only reads (0 $, no fal call): one item per pet with its own media and one per
 *    shared look + stage (generated ONCE — its pets link the look row, 0 $), with the estimated
 *    cost (`clip_seconds.transition` × the transition profile price, 5 s Kling ≈ 0,56 $).
 *  - `run()` queues them through the normal pipeline (SubmitPetStateVideo → FalGateway +
 *    AiSpendGuard → candidate → quality check → compress-on-store → markStored / linkToLook),
 *    after a budget PRE-CHECK of the total; each clip is still checked by the guard at its
 *    submit (a refused one fails, keeps showing the reversal and is listed again). No fal call
 *    here and nothing inside a transaction; cache lock LOCK_KEY; audited as AUDIT_KEY.
 *  - Until a new clip is stored the slot keeps its marker and keeps showing the reversal (no gap
 *    in the preparation, nothing left `running`: a pet slot only waits for its look row the
 *    usual way). markStored / linkToLook clear the marker; `releaseFor()` (called by
 *    PetMediaService after a stored / linked sleeping_to_idle) and every run's `release()` then
 *    delete the reversed derivative row + its file once NO pet (active or not — a reactivated
 *    pet must not lose its clip) is still marked — the file only when no row references it
 *    (VideoCompressionService::isReferenced, the deleteIfUnreferenced pattern). A look row's own
 *    leftover marker is cleared with it, so SchoolClipDerivativeService::reversalWanted() agrees
 *    and never re-makes it (no ffmpeg churn). No other media are touched.
 *
 * Not the only path (QA #456 M1, decided: David wants the reversal gone): every normal
 * generation path — queueStateVideos, Generate missing, a stage remake, ResumeStateMedia,
 * media:retry — also replaces a legacy slot it meets, each clip guarded by AiSpendGuard. The
 * command (never scheduled) is the bulk sweep for the rest; its total is an upper bound that can
 * shrink between the dry run and the real run. Items a run dispatched within RECENT_MINUTES are
 * planned as `wait` (QA #456 m1), so a re-run never queues them twice.
 */
class FrugalUnreverseService
{
    public const TARGET = 'sleeping_to_idle';

    public const SOURCE = 'idle_to_sleeping';

    public const AUDIT_KEY = 'media_frugal_unreverse';

    public const LOCK_KEY = 'media-frugal-unreverse';

    public const LOCK_SECONDS = 60;

    public const ACTION_GENERATE = 'generate';

    public const ACTION_LINK = 'link';

    public const ACTION_WAIT = 'wait';

    /** A slot a run dispatched this recently (audit rows) is `wait`, not queued again. */
    public const RECENT_MINUTES = 30;

    public function __construct(
        private readonly PetMediaService $media,
        private readonly MediaProfiles $profiles,
        private readonly AiSpendGuard $guard,
        private readonly FalAiService $fal,
        private readonly VideoCompressionService $compression,
    ) {}

    /** Estimated cost of one new sleeping_to_idle (the transition profile × its seconds). */
    public function clipCostUsd(): float
    {
        return $this->profiles->clipVideo('transition')->estimatedCostUsd();
    }

    /**
     * The marked slots that would get a real clip, grouped into generation units.
     *
     * @return array{items: list<array{owner: string, stage: string|null, look_row: int|null, slots: list<int>, pets: list<int>, action: string, cost_usd: float}>, generate: int, slots: int, cost_usd: float, releasable: int, more: int}
     */
    public function plan(?int $limit = null): array
    {
        $cost = $this->clipCostUsd();
        $items = [];
        $groups = [];
        $recent = $this->recentlyDispatched();

        $marked = PetMedia::query()
            ->where('kind', PetMedia::KIND_TRANSITION)->where('state', self::TARGET)
            ->where('frugal_source', self::SOURCE)
            ->whereNotNull('pet_id')
            // »Needs review« is decided in the admin panel, never remade from here.
            ->where(fn ($q) => $q->whereNull('error_reason')->orWhere('error_reason', '!=', 'quality_failed'))
            ->whereHas('pet', fn ($q) => $q->where('is_active', true))
            ->with('pet')
            ->orderBy('pet_id')->orderBy('id')
            ->get()
            ->filter(fn (PetMedia $slot) => $this->stillServedReversed($slot))
            ->values();

        foreach ($marked as $slot) {
            $pet = $slot->pet;

            if (! $pet->usesLookPool()) {
                // A unique pet's live claim (a request at fal) is already being made.
                if ($slot->status === PetMedia::STATUS_RUNNING) {
                    continue;
                }
                // Dispatched by a recent run and not failed yet: its job is still in the queue.
                $wait = isset($recent[(int) $slot->id]) && $slot->status === PetMedia::STATUS_PENDING;
                $items[] = ['owner' => "pet {$pet->id}", 'stage' => $pet->life_stage?->value, 'look_row' => null,
                    'slots' => [(int) $slot->id], 'pets' => [(int) $pet->id],
                    'action' => $wait ? self::ACTION_WAIT : self::ACTION_GENERATE, 'cost_usd' => $wait ? 0.0 : $cost];

                continue;
            }

            $key = $pet->pet_look_id.'|'.$pet->life_stage?->value;
            $groups[$key] ??= ['look' => (int) $pet->pet_look_id, 'stage' => $pet->life_stage?->value, 'slots' => [], 'pets' => []];
            $groups[$key]['slots'][] = (int) $slot->id;
            $groups[$key]['pets'][] = (int) $pet->id;
        }

        foreach ($groups as $group) {
            $row = $group['stage'] === null ? null : PetMedia::query()->where('pet_look_id', $group['look'])
                ->where('kind', PetMedia::KIND_TRANSITION)->where('state', self::TARGET)
                ->where('life_stage', $group['stage'])->first();

            if ($row?->needsReview()) {
                continue; // the look's new clip waits for an admin decision
            }

            $dispatched = array_intersect_key($recent, array_flip($group['slots'])) !== [];
            $action = match (true) {
                $row !== null && $row->isShown() && $row->status === PetMedia::STATUS_READY => self::ACTION_LINK,
                $row !== null && $row->status === PetMedia::STATUS_RUNNING && $row->request_id !== null => self::ACTION_WAIT,
                // A recent run queued this look's pets and the look row has not failed since.
                $dispatched && $row?->status !== PetMedia::STATUS_FAILED => self::ACTION_WAIT,
                default => self::ACTION_GENERATE,
            };

            $items[] = ['owner' => "look {$group['look']}", 'stage' => $group['stage'], 'look_row' => $row?->id,
                'slots' => $group['slots'], 'pets' => array_values(array_unique($group['pets'])), 'action' => $action,
                'cost_usd' => $action === self::ACTION_GENERATE ? $cost : 0.0];
        }

        $all = count($items);
        if ($limit !== null && $limit > 0) {
            $items = array_slice($items, 0, $limit);
        }

        return [
            'items' => $items,
            'generate' => count(array_filter($items, fn (array $i) => $i['action'] === self::ACTION_GENERATE)),
            'slots' => array_sum(array_map(fn (array $i) => count($i['slots']), $items)),
            'cost_usd' => round((float) array_sum(array_column($items, 'cost_usd')), 4),
            'releasable' => $this->releasable()->count(),
            'more' => $all - count($items),
        ];
    }

    /**
     * Queue the planned items (recomputed now) and delete the reversals nobody shows any more.
     *
     * @return array{outcome: 'queued'|'nothing'|'ai_off'|'budget'|'busy', queued: int, slots: int, cost_usd: float, released: int}
     */
    public function run(?User $actor = null, ?int $limit = null): array
    {
        $lock = Cache::lock(self::LOCK_KEY, self::LOCK_SECONDS);

        if (! $lock->get()) {
            return ['outcome' => 'busy', 'queued' => 0, 'slots' => 0, 'cost_usd' => 0.0, 'released' => 0];
        }

        try {
            return $this->runLocked($actor, $limit);
        } finally {
            $lock->release();
        }
    }

    /**
     * @return array{outcome: 'queued'|'nothing'|'ai_off'|'budget', queued: int, slots: int, cost_usd: float, released: int}
     */
    private function runLocked(?User $actor, ?int $limit): array
    {
        $released = $this->release();
        $plan = $this->plan($limit);
        $none = ['queued' => 0, 'slots' => 0, 'released' => $released];

        if ($plan['items'] === []) {
            return ['outcome' => 'nothing', 'cost_usd' => 0.0] + $none;
        }

        if (! $this->fal->isEnabled() || FalGateway::balanceExhaustedAt() !== null) {
            return ['outcome' => 'ai_off', 'cost_usd' => $plan['cost_usd']] + $none;
        }

        if ($plan['cost_usd'] > 0 && $this->guard->refusalFor($plan['cost_usd'], AiSpendPurpose::StateVideo) !== null) {
            return ['outcome' => 'budget', 'cost_usd' => $plan['cost_usd']] + $none;
        }

        $queuedItems = [];
        $queuedSlots = [];

        foreach ($plan['items'] as $item) {
            if ($item['action'] === self::ACTION_WAIT) {
                continue; // already at fal or in the queue (a recent run / the pipeline)
            }

            // A shared look's failed row starts a new chain once (its pets follow through the look).
            if ($item['action'] === self::ACTION_GENERATE && $item['look_row'] !== null) {
                $row = PetMedia::find($item['look_row']);
                if ($row !== null && $row->status === PetMedia::STATUS_FAILED) {
                    $this->media->resetForNewGeneration($row, bump: true);
                }
            }

            $any = false;
            foreach ($item['slots'] as $slotId) {
                if ($this->queueSlot($slotId)) {
                    $queuedSlots[] = $slotId;
                    $any = true;
                }
            }
            if ($any) {
                $queuedItems[] = $item;
            }
        }

        if ($queuedItems === []) {
            return ['outcome' => 'nothing', 'cost_usd' => 0.0] + $none;
        }

        $cost = round((float) array_sum(array_column($queuedItems, 'cost_usd')), 4);

        AppSettingChange::create([
            'key' => self::AUDIT_KEY,
            'user_id' => $actor?->id,
            'old' => null,
            'new' => [
                'pet_media_ids' => $queuedSlots,
                'owners' => array_column($queuedItems, 'owner'),
                // Pre-checked against the budget; each clip is still checked by the guard at its submit.
                'estimated_usd' => $cost,
                'released' => $released,
                'limit' => $limit,
            ],
        ]);
        Log::info('FrugalUnreverseService: sleeping_to_idle queued for reversed slots', ['items' => count($queuedItems), 'slots' => count($queuedSlots), 'estimated_usd' => $cost]);

        return ['outcome' => 'queued', 'queued' => count($queuedItems), 'slots' => count($queuedSlots), 'cost_usd' => $cost, 'released' => $released];
    }

    /**
     * One marked pet slot into the normal pipeline: a failed / stale-file slot starts a new
     * generation (conditional reset — a row another worker moved is left alone), a pending or
     * look-waiting one is (re)dispatched. The marker stays until its own clip is stored.
     */
    private function queueSlot(int $slotId): bool
    {
        $slot = PetMedia::find($slotId);
        if ($slot === null || $slot->frugal_source === null) {
            return false;
        }

        if (in_array($slot->status, [PetMedia::STATUS_FAILED, PetMedia::STATUS_READY], true)
            && ! $this->media->resetForNewGeneration($slot, bump: true)) {
            return false;
        }

        // A unique pet's live claim is never touched (its request is already at fal).
        if ($slot->status === PetMedia::STATUS_RUNNING && $slot->request_id !== null) {
            return false;
        }

        SubmitPetStateVideo::dispatch((int) $slot->id);

        return true;
    }

    /**
     * Slot ids a run dispatched within RECENT_MINUTES (from the audit rows).
     *
     * @return array<int, true>
     */
    private function recentlyDispatched(): array
    {
        $ids = [];
        AppSettingChange::query()->where('key', self::AUDIT_KEY)
            ->where('created_at', '>=', now()->subMinutes(self::RECENT_MINUTES))
            ->get(['new'])
            ->each(function (AppSettingChange $change) use (&$ids) {
                foreach ((array) ($change->new['pet_media_ids'] ?? []) as $id) {
                    $ids[(int) $id] = true;
                }
            });

        return $ids;
    }

    /** The pet still uses this transition (state media, the full transition set). */
    private function stillServedReversed(PetMedia $slot): bool
    {
        $pet = $slot->pet;

        // Dogs only: frugal B never marked a cat (a stray marker on a cat is left alone).
        return $pet instanceof Pet && $pet->is_active && $pet->speciesValue() === Species::Dog
            && $this->media->wantsPoseMedia($pet, $slot);
    }

    // ──────────────────────────────────────────────────────────────
    //  Cleanup of the reversed derivatives
    // ──────────────────────────────────────────────────────────────

    /**
     * After a `sleeping_to_idle` row was stored or linked (PetMediaService): delete the reversed
     * derivative of its `idle_to_sleeping` owner when no active pet is served from it any more.
     */
    public function releaseFor(PetMedia $target): int
    {
        $owners = $target->pet_look_id !== null
            ? PetMedia::query()->where('pet_look_id', $target->pet_look_id)->where('life_stage', $target->life_stage)
                ->where('kind', PetMedia::KIND_TRANSITION)->where('state', self::SOURCE)->pluck('id')->all()
            : PetMedia::query()->where('pet_id', $target->pet_id)->where('kind', PetMedia::KIND_TRANSITION)->where('state', self::SOURCE)
                ->get()->map(fn (PetMedia $m) => SchoolClipDerivativeService::ownerId($m))->all();

        if ($owners === []) {
            return 0;
        }

        return $this->releaseRows(PetMediaDerivative::query()->where('key', self::TARGET)->whereIn('pet_media_id', $owners)->get());
    }

    /** Every reversed derivative no active pet is served from any more (each run of the command). */
    public function release(): int
    {
        return $this->releaseRows($this->releasable());
    }

    /** @return Collection<int, PetMediaDerivative> */
    private function releasable(): Collection
    {
        return PetMediaDerivative::query()->where('key', self::TARGET)->orderBy('id')->get()
            ->filter(fn (PetMediaDerivative $d) => ! $this->servedFrom((int) $d->pet_media_id))
            ->values();
    }

    /** @param  Collection<int, PetMediaDerivative>  $rows */
    private function releaseRows(Collection $rows): int
    {
        $released = 0;

        foreach ($rows as $row) {
            if ($this->servedFrom((int) $row->pet_media_id)) {
                continue;
            }

            $path = $row->storage_path;
            // Ordering: the marker check above, then the row, then the file — a crash in between
            // leaves at worst an unreferenced file (disk-report orphan), never a row without a file.
            // The row first (one statement, no transaction needed), then the file if nothing points at it.
            if (PetMediaDerivative::whereKey($row->id)->where('key', self::TARGET)->delete() !== 1) {
                continue;
            }
            $released++;
            $this->clearLookMarker((int) $row->pet_media_id);

            if (filled($path)) {
                try {
                    if (! $this->compression->isReferenced((string) $path)) {
                        $this->media->disk()->delete((string) $path);
                    }
                } catch (Throwable $e) {
                    Log::warning('FrugalUnreverseService: could not delete a reversed clip', ['path' => $path, 'error' => $e->getMessage()]);
                }
            }

            Log::info('FrugalUnreverseService: reversed sleeping_to_idle released', ['pet_media_id' => $row->pet_media_id, 'path' => $path]);
        }

        return $released;
    }

    /**
     * A shared look's sleeping_to_idle row of the owner's stage that no pet is served from any
     * more drops its leftover marker (it has no clip of its own), so reversalWanted() is false
     * and media:school-derivatives never re-makes the reversal just released.
     */
    private function clearLookMarker(int $ownerId): void
    {
        $owner = PetMedia::find($ownerId);
        if ($owner?->pet_look_id === null) {
            return; // a unique pet's sibling is the pet's own (unmarked) slot
        }

        PetMedia::query()->where('pet_look_id', $owner->pet_look_id)->where('life_stage', $owner->life_stage)
            ->where('kind', PetMedia::KIND_TRANSITION)->where('state', self::TARGET)
            ->whereNotNull('frugal_source')->whereNull('storage_path')
            ->update(['frugal_source' => null]);
    }

    /**
     * Is any pet — active or not (QA #456 m2: a reactivated pet keeps its clip) — still shown
     * the reversal of this idle_to_sleeping owner row? (Its sleeping_to_idle slot is still
     * marked — markStored / linkToLook clear the marker.)
     */
    private function servedFrom(int $ownerId): bool
    {
        $owner = PetMedia::find($ownerId);
        if ($owner === null) {
            return false;
        }

        $petIds = $owner->pet_look_id !== null
            ? PetMedia::query()->where('look_media_id', $owner->id)->whereNotNull('pet_id')->pluck('pet_id')->all()
            : array_filter([$owner->pet_id]);

        return $petIds !== [] && PetMedia::query()
            ->whereIn('pet_id', $petIds)
            ->where('kind', PetMedia::KIND_TRANSITION)->where('state', self::TARGET)
            ->whereNotNull('frugal_source')
            ->exists();
    }
}
